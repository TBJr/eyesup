#!/usr/bin/env node
// Turns packages/tokens/tokens.json into CSS custom properties.
// Zero dependencies. Light by default; dark under prefers-color-scheme and
// [data-theme="dark"]; also a [data-theme="high-contrast"] hook.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(join(root, 'packages/tokens/tokens.json'), 'utf8'));
const outPath = join(root, 'packages/tokens/tokens.css');

/** @param {unknown} node @param {string[]} path @param {Record<string, string>} out */
function walk(node, path, out) {
  if (node == null || typeof node !== 'object') return;
  if ('$value' in node) {
    const value = stringifyValue(node.$value);
    if (value != null) out[path.join('-')] = value;
    return;
  }
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    walk(child, [...path, kebab(key)], out);
  }
}

/** @param {string} key */
function kebab(key) {
  return key.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/_/g, '-').toLowerCase();
}

/** @param {unknown} value */
function stringifyValue(value) {
  if (typeof value === 'string' || typeof value === 'number') return String(value);
  if (Array.isArray(value)) return value.map(String).join(', ');
  if (value && typeof value === 'object') {
    // typography composites become individual properties via walk; skip raw object
    return null;
  }
  return null;
}

/** @param {Record<string, string>} map */
function toBlock(map) {
  return Object.entries(map)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, value]) => `  --${name}: ${value};`)
    .join('\n');
}

const light = {};
const dark = {};
const shared = {};

walk(tokens.color?.light, ['color'], light);
walk(tokens.color?.dark, ['color'], dark);

for (const [section, node] of Object.entries(tokens)) {
  if (section === 'color' || section.startsWith('$')) continue;
  walk(node, [kebab(section)], shared);
}

// High-contrast: boost ink/surface contrast from light tokens when present.
const highContrast = {
  ...light,
  'color-ink-primary': '#000000',
  'color-surface-page': '#FFFFFF',
  'color-surface-card': '#FFFFFF',
  'color-accent': '#0000EE',
  'color-state-error': '#B00000',
  'color-state-correct': '#006600',
};

const css = `/* Generated by scripts/build-tokens.mjs — do not edit by hand. */

:root {
${toBlock({ ...light, ...shared })}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${toBlock(dark)}
  }
}

[data-theme="dark"] {
${toBlock(dark)}
}

[data-theme="high-contrast"] {
${toBlock(highContrast)}
}
`;

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, css);
console.log(`Wrote ${outPath}`);
